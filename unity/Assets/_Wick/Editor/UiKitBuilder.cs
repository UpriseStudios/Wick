using System.IO;
using System.Text;
using UnityEditor;
using UnityEngine;
using Wick.Editor.ArtPipeline;

namespace Wick.Editor
{
    /// <summary>
    /// The UI kit: 9-sliced button, row and panel sprites at 3x (the panels' reference resolution is
    /// 1080 x 1920, so 3x maps one to one), from Art/Incoming/ui/&lt;id&gt;/&lt;id&gt;@3x.png when supplied, else
    /// stand-ins in the palette (thick Ink Brown outline, Parchment, Candle Flame, Trap Teal, Danger
    /// Red, a glossy top band). Writes Game/UI/UiKit.uss, which both screens load after their own
    /// styles, so the layout stays and only the look changes.
    /// Menu: Wick > Art > Build UI Kit. Also run by Wick > Rebuild Placeholder Content.
    /// </summary>
    public static class UiKitBuilder
    {
        private const string Root = "Assets/_Wick";
        private const string StandInDir = Root + "/Art/StandIns/UI";
        public const string UssPath = Root + "/Game/UI/UiKit.uss";
        private const int Size = 120, Border = 42;

        private static readonly Color Ink = Hex(0x2B1D14), Parchment = Hex(0xF7E7C1), Flame = Hex(0xFF9F1C);
        private static readonly Color Teal = Hex(0x3EC6E0), Danger = Hex(0xE5484D), Gold = Hex(0xF2C14E);

        [MenuItem("Wick/Art/Build UI Kit")]
        public static void BuildMenu()
        {
            Build();
            AssetDatabase.SaveAssets();
            Debug.Log("UiKitBuilder: UI kit and UiKit.uss rebuilt.");
        }

        public static void Build()
        {
            Directory.CreateDirectory(StandInDir);
            string primary = Sprite("ui_button_primary", Flame, 7, gloss: true);
            string secondary = Sprite("ui_button_secondary", Teal, 7, gloss: true);
            string danger = Sprite("ui_button_danger", Danger, 7, gloss: true);
            string row = Sprite("ui_row", Parchment, 5, gloss: false);
            string panel = Sprite("ui_panel", Parchment, 7, gloss: false, trim: true);

            var uss = new StringBuilder();
            uss.AppendLine("/* Generated by Wick > Art > Build UI Kit (Editor/UiKitBuilder.cs). Loaded after each screen's own styles. */");
            uss.AppendLine();
            Rule(uss, ".wide-button, .log-button, .share-button, .bar-button, .action, .small-button, .sel-button, .tab", primary,
                "color: rgb(43, 29, 20);");
            Rule(uss, ".wide-button.secondary, .tab.off", secondary, "color: rgb(43, 29, 20);");
            Rule(uss, ".log-button.revenge", danger, "color: rgb(255, 245, 235);");
            Rule(uss, ".log-row, .draft-row, .issue-row", row, "");
            Rule(uss, ".card", panel, "");
            uss.AppendLine(".log-row .log-text, .draft-row, .issue-row { color: rgb(43, 29, 20); }");
            uss.AppendLine(".log-row .log-text.held { color: rgb(30, 110, 60); }");
            uss.AppendLine(".log-row .log-text.robbed { color: rgb(170, 40, 45); }");
            uss.AppendLine(".wide-button:disabled, .log-button:disabled { opacity: 0.45; }");
            File.WriteAllText(UssPath, uss.ToString());
            AssetDatabase.ImportAsset(UssPath, ImportAssetOptions.ForceSynchronousImport);
        }

        private static void Rule(StringBuilder uss, string selector, string spriteUrl, string extra)
        {
            uss.AppendLine(selector + " {");
            uss.AppendLine("    background-image: " + spriteUrl + ";");
            uss.AppendLine("    background-color: rgba(0, 0, 0, 0);");
            uss.AppendLine("    border-width: 0;");
            uss.AppendLine("    border-radius: 0;");
            if (extra.Length > 0)
            {
                uss.AppendLine("    " + extra);
            }

            uss.AppendLine("}");
            uss.AppendLine();
        }

        /// <summary>The kit sprite as a USS url (real art when supplied), with its 9-slice border set.</summary>
        private static string Sprite(string id, Color fill, int outline, bool gloss, bool trim = false)
        {
            string path = ArtBudgets.IncomingRoot + "/ui/" + id + "/" + id + "@3x.png";
            if (!File.Exists(path))
            {
                path = StandInDir + "/" + id + ".png";
                File.WriteAllBytes(path, Draw(fill, outline, gloss, trim).EncodeToPNG());
                AssetDatabase.ImportAsset(path, ImportAssetOptions.ForceSynchronousImport);
            }

            var importer = (TextureImporter)AssetImporter.GetAtPath(path);
            importer.textureType = TextureImporterType.Sprite;
            importer.spriteImportMode = SpriteImportMode.Single;
            importer.mipmapEnabled = false;
            importer.alphaIsTransparency = true;
            if (importer.spriteBorder == Vector4.zero)
            {
                // A third of the sprite on each side, unless the artist set the slices.
                importer.GetSourceTextureWidthAndHeight(out int w, out int h);
                float b = Mathf.Round(Mathf.Min(w, h) * Border / (float)Size);
                importer.spriteBorder = new Vector4(b, b, b, b);
            }

            importer.SaveAndReimport();
            string guid = AssetDatabase.AssetPathToGUID(path);
            return "url(\"project://database/" + path + "?fileID=21300000&guid=" + guid + "&type=3#" + Path.GetFileNameWithoutExtension(path) + "\")";
        }

        /// <summary>A chunky rounded rectangle: outline, fill, a lighter top band and a darker base.</summary>
        private static Texture2D Draw(Color fill, int outline, bool gloss, bool trim)
        {
            var tex = new Texture2D(Size, Size, TextureFormat.RGBA32, false);
            const float radius = 34f;
            for (int y = 0; y < Size; y++)
            {
                for (int x = 0; x < Size; x++)
                {
                    float d = RoundedDistance(x + 0.5f, y + 0.5f, radius); // > 0 inside, in pixels from the edge
                    Color c = Color.clear;
                    if (d > 0f)
                    {
                        float v = y / (float)Size; // 0 bottom, 1 top
                        Color body = fill;
                        if (gloss && v > 0.62f && d > outline + 4)
                        {
                            body = Color.Lerp(fill, Color.white, 0.35f);
                        }
                        else if (v < 0.18f)
                        {
                            body = Color.Lerp(fill, Ink, 0.18f);
                        }

                        if (trim && d > outline + 8 && d < outline + 12)
                        {
                            body = Gold;
                        }

                        c = d <= outline ? Ink : body;
                        c.a = Mathf.Clamp01(d); // soft outer edge
                    }

                    tex.SetPixel(x, y, c);
                }
            }

            tex.Apply();
            return tex;
        }

        /// <summary>Distance in pixels inside a rounded rectangle filling the sprite (negative outside).</summary>
        private static float RoundedDistance(float x, float y, float r)
        {
            float half = Size / 2f;
            float qx = Mathf.Abs(x - half) - (half - r);
            float qy = Mathf.Abs(y - half) - (half - r);
            float outside = new Vector2(Mathf.Max(qx, 0f), Mathf.Max(qy, 0f)).magnitude;
            return -(outside + Mathf.Min(Mathf.Max(qx, qy), 0f) - r);
        }

        private static Color Hex(int rgb)
        {
            return new Color(((rgb >> 16) & 255) / 255f, ((rgb >> 8) & 255) / 255f, (rgb & 255) / 255f);
        }
    }
}
